package ru.vlad.triliumnotes.capture

import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.net.Uri
import android.provider.OpenableColumns
import android.util.AtomicFile
import androidx.core.content.FileProvider
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.io.IOException
import java.util.Locale
import java.util.UUID

/** A neutral, private inbox. No session, credential or server is opened while receiving a share. */
data class CapturedAttachment(val id: String, val title: String, val mime: String, val size: Long)
data class PendingCapture(
    val id: String,
    val title: String,
    val text: String,
    val attachments: List<CapturedAttachment>,
    val accountId: String? = null,
    val targetNoteId: String? = null,
    val textApplied: Boolean = false,
    val appliedAttachmentIds: Set<String> = emptySet(),
    val targetParentId: String? = null,
    val targetTitle: String? = null,
    val createNew: Boolean = false,
)

class CaptureInbox(context: Context) {
    private val context = context.applicationContext
    private val directory = File(this.context.filesDir, "capture-inbox").apply { mkdirs() }
    private val mutable = MutableStateFlow<List<PendingCapture>>(emptyList())
    val entries = mutable.asStateFlow()
    init { refresh() }

    fun refresh() = synchronized(LOCK) {
        mutable.value = directory.listFiles().orEmpty().filter { it.isDirectory && validId(it.name) && !File(directory, "${it.name}.done").exists() }
            .sortedBy { it.lastModified() }.mapNotNull { folder ->
                runCatching { read(folder).takeIf { metadata(folder).optBoolean("complete") } }.getOrNull()
            }
    }

    /** id is generated by the receiver, retained across recreation, and never taken from an exported extra. */
    fun receive(intent: Intent, id: String): PendingCapture? = synchronized(LOCK) {
        require(validId(id))
        require(intent.action == Intent.ACTION_SEND || intent.action == Intent.ACTION_SEND_MULTIPLE)
        require(validMime(intent.type))
        if (File(directory, "$id.done").exists()) return@synchronized null
        val folder = File(directory, id).apply { mkdirs() }
        val previous = runCatching { read(folder) }.getOrNull()
        if (runCatching { metadata(folder).optBoolean("complete") }.getOrDefault(false)) return@synchronized previous
        val uris = shareUris(intent)
        require(uris.size <= MAX_FILES)
        require(uris.isEmpty() || intent.flags and Intent.FLAG_GRANT_READ_URI_PERMISSION != 0)
        uris.forEach(::validateExternalUri)
        val text = intent.getCharSequenceExtra(Intent.EXTRA_TEXT)?.toString().orEmpty()
        val title = intent.getCharSequenceExtra(Intent.EXTRA_SUBJECT)?.toString().orEmpty().take(512)
        require(text.length <= MAX_TEXT_LENGTH)
        require(text.isNotBlank() || uris.isNotEmpty())
        var capture = previous ?: PendingCapture(id, title, text, emptyList())
        save(folder, capture, complete = false)
        var total = capture.attachments.sumOf { it.size }
        uris.forEachIndexed { index, uri ->
            val attachmentId = index.toString()
            if (capture.attachments.any { it.id == attachmentId }) return@forEachIndexed
            val resolver = context.contentResolver
            val suppliedName = resolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use {
                if (it.moveToFirst() && !it.isNull(0)) it.getString(0) else null
            }
            val name = safeTitle(suppliedName ?: "attachment-${index + 1}")
            val mime = resolver.getType(uri)?.substringBefore(';')?.trim()?.lowercase(Locale.ROOT)
                ?.takeIf { validMime(it) && '*' !in it } ?: intent.type?.takeIf { validMime(it) && '*' !in it } ?: "application/octet-stream"
            val output = AtomicFile(File(folder, "part-$attachmentId"))
            val stream = output.startWrite()
            var size = 0L
            try {
                (resolver.openInputStream(uri) ?: throw IOException("Missing share stream")).use { input ->
                    val buffer = ByteArray(64 * 1024)
                    while (true) {
                        val count = input.read(buffer)
                        if (count < 0) break
                        size += count
                        if (total + size > MAX_BYTES) throw IOException("Share exceeds inbox limit")
                        stream.write(buffer, 0, count)
                    }
                }
                output.finishWrite(stream)
            } catch (error: Throwable) { output.failWrite(stream); throw error }
            total += size
            capture = capture.copy(attachments = capture.attachments + CapturedAttachment(attachmentId, name, mime, size))
            save(folder, capture, complete = false)
        }
        save(folder, capture, complete = true)
        refresh()
        capture
    }

    fun bindTarget(id: String, accountId: String, noteId: String, parentId: String? = null, title: String? = null) = update(id) {
        require(accountId.isNotBlank() && noteId.matches(Regex("[A-Za-z0-9_]{4,32}")))
        require(it.accountId == null || it.accountId == accountId) { "Capture belongs to another account" }
        require(it.targetNoteId == null || it.targetNoteId == noteId) { "Capture destination already chosen" }
        if (it.targetNoteId != null) {
            require(it.targetParentId == parentId && it.targetTitle == title) { "Capture destination already chosen" }
            it
        } else it.copy(accountId = accountId, targetNoteId = noteId, targetParentId = parentId,
            targetTitle = title, createNew = parentId != null)
    }
    fun markTextApplied(id: String) = update(id) {
        require(it.accountId != null && it.targetNoteId != null)
        it.copy(textApplied = true)
    }
    fun markAttachmentApplied(id: String, attachmentId: String) = update(id) {
        require(it.accountId != null && it.targetNoteId != null)
        require(it.attachments.any { attachment -> attachment.id == attachmentId })
        it.copy(appliedAttachmentIds = it.appliedAttachmentIds + attachmentId)
    }
    fun complete(id: String) = synchronized(LOCK) {
        val capture = read(folder(id))
        require(capture.textApplied && capture.attachments.all { it.id in capture.appliedAttachmentIds })
        discard(id)
    }
    /** Explicit user cancellation, or successful delivery. A tombstone prevents activity replay. */
    fun discard(id: String) = synchronized(LOCK) {
        val folder = folder(id)
        val tombstone = AtomicFile(File(directory, "$id.done"))
        val stream = tombstone.startWrite()
        try { stream.write(1); tombstone.finishWrite(stream) }
        catch (error: Throwable) { tombstone.failWrite(stream); throw error }
        folder.deleteRecursively()
        refresh()
    }
    fun attachmentFile(id: String, attachmentId: String): File = synchronized(LOCK) {
        val folder = folder(id)
        require(read(folder).attachments.any { it.id == attachmentId })
        File(folder, "part-$attachmentId").also { require(it.isFile) }
    }
    fun attachmentUri(id: String, attachmentId: String): Uri =
        FileProvider.getUriForFile(context, "${context.packageName}.files", attachmentFile(id, attachmentId))

    private fun update(id: String, transform: (PendingCapture) -> PendingCapture) = synchronized(LOCK) {
        val folder = folder(id)
        save(folder, transform(read(folder)), complete = true)
        refresh()
    }
    private fun folder(id: String): File { require(validId(id)); return File(directory, id) }
    private fun metadata(folder: File) = JSONObject(AtomicFile(File(folder, "capture.json")).readFully().toString(Charsets.UTF_8))
    private fun read(folder: File): PendingCapture {
        val data = metadata(folder)
        val parts = data.getJSONArray("attachments")
        val applied = data.optJSONArray("applied") ?: JSONArray()
        return PendingCapture(folder.name, data.getString("title"), data.getString("text"),
            (0 until parts.length()).map { index -> parts.getJSONObject(index).let {
                CapturedAttachment(it.getString("id"), it.getString("title"), it.getString("mime"), it.getLong("size"))
            } }, data.optString("accountId").takeIf(String::isNotEmpty), data.optString("targetNoteId").takeIf(String::isNotEmpty),
            data.optBoolean("textApplied"), (0 until applied.length()).map { applied.getString(it) }.toSet(),
            data.optString("targetParentId").takeIf(String::isNotEmpty), data.optString("targetTitle").takeIf { data.has("targetTitle") && !data.isNull("targetTitle") },
            data.optBoolean("createNew"))
    }
    private fun save(folder: File, capture: PendingCapture, complete: Boolean) {
        val data = JSONObject().put("complete", complete).put("title", capture.title).put("text", capture.text)
            .put("accountId", capture.accountId ?: "").put("targetNoteId", capture.targetNoteId ?: "")
            .put("targetParentId", capture.targetParentId ?: "").put("targetTitle", capture.targetTitle ?: JSONObject.NULL)
            .put("createNew", capture.createNew).put("textApplied", capture.textApplied).put("applied", JSONArray(capture.appliedAttachmentIds.toList()))
            .put("attachments", JSONArray(capture.attachments.map {
                JSONObject().put("id", it.id).put("title", it.title).put("mime", it.mime).put("size", it.size)
            }))
        val output = AtomicFile(File(folder, "capture.json"))
        val stream = output.startWrite()
        try { stream.write(data.toString().toByteArray(Charsets.UTF_8)); output.finishWrite(stream) }
        catch (error: Throwable) { output.failWrite(stream); throw error }
    }
    private fun validateExternalUri(uri: Uri) {
        require(uri.scheme == "content" && !uri.authority.isNullOrBlank()) { "Only granted content URIs are supported" }
        require(uri.authority != "${context.packageName}.files") { "Private app content cannot be shared back" }
        val provider = context.packageManager.resolveContentProvider(uri.authority!!, PackageManager.MATCH_DEFAULT_ONLY)
        require(provider?.applicationInfo?.uid != context.applicationInfo.uid) { "Private provider cannot be imported" }
    }
    companion object {
        private val LOCK = Any()
        private const val MAX_FILES = 128
        private const val MAX_BYTES = 512L * 1024 * 1024
        private const val MAX_TEXT_LENGTH = 4 * 1024 * 1024
        internal fun validId(id: String) = runCatching { UUID.fromString(id).toString() == id }.getOrDefault(false)
        internal fun validMime(value: String?) = value != null && value.length <= 127 && value.matches(Regex("[a-zA-Z0-9!#$&^_.+*\\-]+/[a-zA-Z0-9!#$&^_.+*\\-]+"))
        internal fun safeTitle(value: String) = value.substringAfterLast('/').substringAfterLast('\\')
            .filter { !it.isISOControl() }.trim().take(240).ifBlank { "attachment" }
        @Suppress("DEPRECATION")
        internal fun shareUris(intent: Intent): List<Uri> {
            val streams = if (intent.action == Intent.ACTION_SEND_MULTIPLE)
                intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM).orEmpty()
            else listOfNotNull(intent.getParcelableExtra<Uri>(Intent.EXTRA_STREAM))
            val clip = intent.clipData
            return (streams + (0 until (clip?.itemCount ?: 0)).mapNotNull { clip?.getItemAt(it)?.uri }).distinct()
        }
    }
}
